SelfLearningTransfer::SelfLearningTransfer(SelfLearningDatabase& db) : db_(db) {}

Result<WeightTransferStats> SelfLearningTransfer::transfer(
    SelfLearningDatabase& db,
    const Mesh& sourceMesh,
    const Skeleton& sourceSkeleton,
    const Gr2CharacterProfile& sourceProfile,
    Mesh& targetMesh,
    Skeleton& targetSkeleton,
    const Gr2CharacterProfile& targetProfile,
    uint32_t kNearest,
    const std::set<uint32_t>* lockedBones) {
    
    WeightTransferStats stats;
    stats.verticesProcessed = 0;
    stats.verticesMapped = 0;
    stats.verticesUnmapped = 0;
    stats.avgDistance = 0.0;
    stats.removedMass = 0.0;
    
    // Build bone mapping using learned patterns
    std::vector<int> boneMap(targetSkeleton.bones.size(), -1);
    for (size_t t = 0; t < targetSkeleton.bones.size(); ++t) {
        const std::string& targetBone = targetSkeleton.bones[t].name;
        // Find source bone that maps to this target
        for (size_t s = 0; s < sourceSkeleton.bones.size(); ++s) {
            const std::string& sourceBone = sourceSkeleton.bones[s].name;
            auto mapping = db.getBestMapping(sourceProfile, targetProfile, sourceBone);
            if (mapping && *mapping == targetBone) {
                boneMap[t] = static_cast<int>(s);
                break;
            }
        }
        // Fallback: exact name match
        if (boneMap[t] == -1) {
            for (size_t s = 0; s < sourceSkeleton.bones.size(); ++s) {
                if (sourceSkeleton.bones[s].name == targetBone) {
                    boneMap[t] = static_cast<int>(s);
                    break;
                }
            }
        }
    }
    
    // Transfer weights using kNN with learned affinities
    double totalDist = 0.0;
    for (size_t v = 0; v < targetMesh.vertices.size(); ++v) {
        stats.verticesProcessed++;
        const Vec3& vertPos = targetMesh.vertices[v].position;
        
        // Find k nearest bones using learned patterns
        auto nearest = findNearestBonesLearned(vertPos, targetSkeleton, targetProfile, kNearest);
        if (nearest.empty()) {
            stats.verticesUnmapped++;
            continue;
        }
        
        // Apply learned affinities if available
        applyLearnedAffinities(targetMesh, targetSkeleton, targetProfile);
        
        // Standard kNN transfer
        std::vector<BoneInfluence> newInfluences;
        float totalWeight = 0.0f;
        
        for (const auto& [boneIdx, dist] : nearest) {
            if (lockedBones && lockedBones->count(boneIdx)) continue;
            if (boneMap[boneIdx] == -1) continue;
            
            size_t srcBoneIdx = static_cast<size_t>(boneMap[boneIdx]);
            
            // Find corresponding vertex in source (simplified: nearest by position)
            float bestDist = std::numeric_limits<float>::max();
            size_t bestSrcVert = 0;
            for (size_t sv = 0; sv < sourceMesh.vertices.size(); ++sv) {
                float d = distance(vertPos, sourceMesh.vertices[sv].position);
                if (d < bestDist) {
                    bestDist = d;
                    bestSrcVert = sv;
                }
            }
            
            // Get weight from source vertex for mapped bone
            for (const auto& inf : sourceMesh.vertices[bestSrcVert].influences) {
                if (inf.bone == srcBoneIdx) {
                    float w = inf.weight * (1.0f / (1.0f + dist * 10.0f)); // Distance falloff
                    newInfluences.push_back({static_cast<uint32_t>(boneIdx), w});
                    totalWeight += w;
                    totalDist += dist;
                    break;
                }
            }
        }
        
        // Normalize and clamp to 4 influences
        if (!newInfluences.empty()) {
            std::sort(newInfluences.begin(), newInfluences.end(),
                     [](const BoneInfluence& a, const BoneInfluence& b) {
                         return a.weight > b.weight;
                     });
            
            if (newInfluences.size() > 4) {
                float excess = 0.0f;
                for (size_t i = 4; i < newInfluences.size(); ++i) {
                    excess += newInfluences[i].weight;
                }
                stats.removedMass += excess;
                newInfluences.resize(4);
            }
            
            // Renormalize
            float sum = 0.0f;
            for (auto& inf : newInfluences) sum += inf.weight;
            if (sum > 0.0f) {
                for (auto& inf : newInfluences) inf.weight /= sum;
            }
            
            targetMesh.vertices[v].influences = std::move(newInfluences);
            stats.verticesMapped++;
        } else {
            stats.verticesUnmapped++;
        }
    }
    
    if (stats.verticesMapped > 0) {
        stats.avgDistance = totalDist / stats.verticesMapped;
    }
    
    return Result<WeightTransferStats>::ok(stats);
}

Result<AutoRigStats> SelfLearningTransfer::autoRig(
    SelfLearningDatabase&,  // db (unused, uses db_ member)
    Mesh& mesh,
    Skeleton& skeleton,
    const Gr2CharacterProfile& profile,
    float maxDistance,
    const std::set<uint32_t>* lockedBones) {
    
    AutoRigStats stats;
    stats.verticesBound = 0;
    stats.avgDistance = 0.0;
    stats.maxDistance = 0.0;
    stats.removedMass = 0.0;
    
    // Apply learned vertex affinities
    applyLearnedAffinities(mesh, skeleton, profile);
    
    // For vertices without learned affinities, use distance-based assignment
    double totalDist = 0.0;
    for (size_t v = 0; v < mesh.vertices.size(); ++v) {
        if (!mesh.vertices[v].influences.empty()) {
            stats.verticesBound++;
            continue;
        }
        
        const Vec3& vertPos = mesh.vertices[v].position;
        auto nearest = findNearestBonesLearned(vertPos, skeleton, profile, 4);
        
        std::vector<BoneInfluence> influences;
        float totalDistV = 0.0f;
        
        for (const auto& [boneIdx, dist] : nearest) {
            if (lockedBones && lockedBones->count(boneIdx)) continue;
            if (dist > maxDistance) continue;
            
            float weight = 1.0f / (1.0f + dist * 20.0f);
            influences.push_back({static_cast<uint32_t>(boneIdx), weight});
            totalDistV += dist;
        }
        
        if (!influences.empty()) {
            // Normalize
            float sum = 0.0f;
            for (auto& inf : influences) sum += inf.weight;
            if (sum > 0.0f) {
                for (auto& inf : influences) inf.weight /= sum;
            }
            
            // Clamp to 4
            if (influences.size() > 4) influences.resize(4);
            
            mesh.vertices[v].influences = std::move(influences);
            stats.verticesBound++;
            double avgDistV = totalDistV / influences.size();
            totalDist += avgDistV;
            stats.maxDistance = std::max(stats.maxDistance, avgDistV);
        }
    }
    
    if (stats.verticesBound > 0) {
        stats.avgDistance = totalDist / stats.verticesBound;
    }
    
    // Count bones used
    std::set<uint32_t> usedBones;
    for (const auto& v : mesh.vertices) {
        for (const auto& inf : v.influences) {
            usedBones.insert(inf.bone);
        }
    }
    
    return Result<AutoRigStats>::ok(stats);
}

std::vector<std::pair<uint32_t, float>> SelfLearningTransfer::findNearestBonesLearned(
    const Vec3& vertexPos,
    const Skeleton& skeleton,
    const Gr2CharacterProfile& profile,
    uint32_t k) const {
    
    std::string key = profile.profileId.empty() 
        ? (profile.race + "_" + profile.gender + "_" + profile.variant)
        : profile.profileId;
    const LearningEntry* entry = db_.getEntry(key);
    
    std::vector<std::pair<uint32_t, float>> candidates;
    candidates.reserve(skeleton.bones.size());
    
    for (size_t b = 0; b < skeleton.bones.size(); ++b) {
        const Bone& bone = skeleton.bones[b];
        Vec3 bonePos{bone.globalTransform.m[3][0], bone.globalTransform.m[3][1], bone.globalTransform.m[3][2]};
        float dist = distance(vertexPos, bonePos);
        
        // Boost confidence if bone has learned affinity
        float confidence = 1.0f;
        if (entry) {
            for (const auto& aff : entry->vertexAffinities) {
                if (aff.boneName == bone.name) {
                    confidence = 1.0f + aff.influenceRadius * 0.1f; // Boost for learned bones
                    dist *= 0.8f; // Reduce effective distance
                    break;
                }
            }
        }
        
        candidates.emplace_back(static_cast<uint32_t>(b), dist / confidence);
    }
    
    std::partial_sort(candidates.begin(), 
                     candidates.begin() + std::min(k, static_cast<uint32_t>(candidates.size())),
                     candidates.end(),
                     [](const auto& a, const auto& b) { return a.second < b.second; });
    
    candidates.resize(std::min(k, static_cast<uint32_t>(candidates.size())));
    return candidates;
}

void SelfLearningTransfer::applyLearnedAffinities(
    Mesh& mesh,
    const Skeleton& skeleton,
    const Gr2CharacterProfile& profile) const {
    
    std::string key = profile.profileId.empty() 
        ? (profile.race + "_" + profile.gender + "_" + profile.variant)
        : profile.profileId;
    const LearningEntry* entry = db_.getEntry(key);
    if (!entry) return;
    
    // Build bone name to index map
    std::unordered_map<std::string, uint32_t> boneIndex;
    for (size_t i = 0; i < skeleton.bones.size(); ++i) {
        boneIndex[skeleton.bones[i].name] = static_cast<uint32_t>(i);
    }
    
    for (const auto& affinity : entry->vertexAffinities) {
        auto it = boneIndex.find(affinity.boneName);
        if (it == boneIndex.end()) continue;
        
        uint32_t boneIdx = it->second;
        
        for (const auto& [vertIdx, weight] : affinity.vertexWeights) {
            if (vertIdx >= mesh.vertices.size()) continue;
            
            // Add or update influence
            auto& influences = mesh.vertices[vertIdx].influences;
            bool found = false;
            for (auto& inf : influences) {
                if (inf.bone == boneIdx) {
                    inf.weight = std::max(inf.weight, weight);
                    found = true;
                    break;
                }
            }
            if (!found) {
                influences.push_back({boneIdx, weight});
            }
        }
    }
}

