void SelfLearningDatabase::updateEntryStats(LearningEntry& entry) {
    entry.totalSamples = static_cast<uint32_t>(entry.transferPatterns.size());
    entry.successfulTransfers = 0;
    for (const auto& p : entry.transferPatterns) {
        if (p.successRate > 0.5f) entry.successfulTransfers += p.sampleCount;
    }
    entry.lastUpdated = 0.0;  // Reserved (always 0): wall-clock timestamps
                              // would break deterministic .m2learn round-trips; the field is
                              // never read, kept for format compatibility.
}

void SelfLearningDatabase::printStats() const {
    std::cout << "=== Self-Learning Database Stats ===\n";
    std::cout << "Entries: " << entries_.size() << "\n";
    for (const auto& [key, entry] : entries_) {
        std::cout << "  [" << key << "] samples=" << entry.totalSamples 
                  << " successful=" << entry.successfulTransfers
                  << " patterns=" << entry.transferPatterns.size()
                  << " affinities=" << entry.vertexAffinities.size() << "\n";
    }
}

