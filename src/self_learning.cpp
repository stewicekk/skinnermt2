Gr2BatchAnalyzer::Gr2BatchAnalyzer(SelfLearningDatabase& db) : db_(db) {}

ResultVoid Gr2BatchAnalyzer::analyzeDirectory(const std::filesystem::path& dirPath) {
    if (!std::filesystem::exists(dirPath)) {
        return ResultVoid::fail("Directory does not exist: " + dirPath.string(), "GR2_ANALYZE");
    }
    
    results_.clear();
    
    for (const auto& entry : std::filesystem::recursive_directory_iterator(dirPath)) {
        if (entry.is_regular_file() && entry.path().extension() == ".gr2") {
            processGr2File(entry.path());
        }
    }
    
    return ResultVoid::ok();
}

ResultVoid Gr2BatchAnalyzer::analyzeBonesPresets(const std::filesystem::path& bonesDir) {
    // Analyze SMD/FBX files exported from 00-BONES 3ds Max presets
    if (!std::filesystem::exists(bonesDir)) {
        return ResultVoid::fail("Bones directory does not exist: " + bonesDir.string(), "GR2_ANALYZE");
    }
    
    for (const auto& entry : std::filesystem::recursive_directory_iterator(bonesDir)) {
        if (entry.is_regular_file()) {
            std::string ext = entry.path().extension().string();
            std::transform(ext.begin(), ext.end(), ext.begin(),
               [](unsigned char c) { return static_cast<char>(std::tolower(c)); });
            if (ext == ".smd" || ext == ".fbx") {
                // Could parse and analyze these too
            }
        }
    }
    
    return ResultVoid::ok();
}

ResultVoid Gr2BatchAnalyzer::buildInitialDatabase() {
    for (const auto& result : results_) {
        if (!result.success) continue;
        
        LearningEntry* entry = db_.getOrCreateEntry(result.profile);
        
        // Extract bone hierarchy
        extractBoneHierarchy(result.parseResult, *entry);
        
        // Extract vertex affinities from mesh
        if (result.parseResult.hasMesh && !result.parseResult.meshes.empty()) {
            // Convert first mesh and skeleton to m2rig format
            auto skel = parser_.toSkeleton(result.parseResult);
            auto mesh = parser_.toMesh(result.parseResult, 0);
            if (skel && mesh) {
                extractVertexAffinities(result.parseResult, *entry);
                detectSymmetryPairs(result.parseResult, *entry);
            }
        }
    }
    
    return ResultVoid::ok();
}

ResultVoid Gr2BatchAnalyzer::exportReport(const std::filesystem::path& outputPath) const {
    std::ofstream file(outputPath);
    if (!file) {
        return ResultVoid::fail("Cannot write report: " + outputPath.string(), "GR2_ANALYZE");
    }
    
    file << "# GR2 Batch Analysis Report\n";
    file << "# Files analyzed: " << results_.size() << "\n\n";
    
    for (const auto& r : results_) {
        file << "## " << r.filename << "\n";
        file << "  Profile: " << r.profile.profileId << " (" << r.profile.race << "/" << r.profile.gender << ")\n";
        file << "  Success: " << (r.success ? "YES" : "NO") << "\n";
        if (!r.success) {
            file << "  Error: " << r.error << "\n";
        } else {
            file << "  Bones: " << r.parseResult.bones.size() << "\n";
            file << "  Meshes: " << r.parseResult.meshes.size() << "\n";
            file << "  Has Weights: " << (r.parseResult.hasWeights ? "YES" : "NO") << "\n";
            file << "  Has Animation: " << (r.parseResult.hasAnimation ? "YES" : "NO") << "\n";
        }
        file << "\n";
    }
    
    return ResultVoid::ok();
}

void Gr2BatchAnalyzer::processGr2File(const std::filesystem::path& filePath) {
    AnalysisResult result;
    result.filename = filePath.filename().string();
    
    auto parseResult = parser_.parse(filePath.string());
    if (!parseResult) {
        result.success = false;
        result.error = parseResult.error().message;
        results_.push_back(std::move(result));
        return;
    }
    
    result.parseResult = std::move(parseResult.value());
    result.profile = detectGr2Character(result.filename, result.parseResult);
    result.success = true;
    results_.push_back(std::move(result));
}

void Gr2BatchAnalyzer::extractBoneHierarchy(const Gr2ParseResult& result, LearningEntry& entry) {
    entry.socketBones.clear();
    entry.weaponBones.clear();
    
    for (const auto& bone : result.bones) {
        if (bone.isSocket) entry.socketBones.push_back(bone.name);
        if (bone.isWeapon) entry.weaponBones.push_back(bone.name);
    }
}

void Gr2BatchAnalyzer::extractVertexAffinities(const Gr2ParseResult& result, LearningEntry& entry) {
    // Extract basic bone position info
    for (const auto& bone : result.bones) {
        LearningEntry::VertexAffinity affinity;
        affinity.boneName = bone.name;
        affinity.bonePosition = bone.position;
        affinity.influenceRadius = bone.length;
        entry.vertexAffinities.push_back(std::move(affinity));
    }
}

void Gr2BatchAnalyzer::detectSymmetryPairs(const Gr2ParseResult& result, LearningEntry& entry) {
    entry.symmetryPairs.clear();
    
    // Common Metin2 symmetry patterns
    std::unordered_map<std::string, std::string> leftToRight = {
        {"L_", "R_"}, {"Left", "Right"}, {"_L", "_R"}, {"_l", "_r"},
        {"l_", "r_"}, {"left_", "right_"}
    };
    
    std::set<std::string> boneNames;
    for (const auto& bone : result.bones) {
        boneNames.insert(bone.name);
    }
    
    for (const auto& name : boneNames) {
        for (const auto& [left, right] : leftToRight) {
            if (name.rfind(left, 0) == 0) { // starts with left prefix
                std::string rightName = right + name.substr(left.size());
                if (boneNames.count(rightName)) {
                    entry.symmetryPairs.emplace_back(name, rightName);
                }
            } else if (name.size() >= left.size() && 
                       name.compare(name.size() - left.size(), left.size(), left) == 0) { // ends with left suffix
                std::string rightName = name.substr(0, name.size() - left.size()) + right;
                if (boneNames.count(rightName)) {
                    entry.symmetryPairs.emplace_back(name, rightName);
                }
            }
        }
    }
}

