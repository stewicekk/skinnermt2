ResultVoid SelfLearningDatabase::load(const std::filesystem::path& path) {
    dbPath_ = path;
    if (!std::filesystem::exists(path)) {
        return ResultVoid::ok(); // Empty database is valid
    }
    
    std::ifstream file(path, std::ios::binary);
    if (!file) {
        return ResultVoid::fail("Cannot open learning database: " + path.string(), "SELF_LEARN");
    }
    
    // Simple text-based format for now
    std::string line;
    LearningEntry* currentEntry = nullptr;
    
    while (std::getline(file, line)) {
        if (line.empty() || line[0] == '#') continue;
        
        if (line.rfind("ENTRY:", 0) == 0) {
            std::string key = line.substr(6);
            currentEntry = getOrCreateEntryByKey(key);
        } else if (currentEntry && line.rfind("BONEMAP:", 0) == 0) {
            // Format: BONEMAP:source->target:confidence
            std::string rest = line.substr(8);
            size_t arrow = rest.find("->");
            size_t colon = rest.rfind(':');
            if (arrow != std::string::npos && colon != std::string::npos && colon > arrow) {
                std::string src = rest.substr(0, arrow);
                std::string tgt = rest.substr(arrow + 2, colon - arrow - 2);
                float conf = std::stof(rest.substr(colon + 1));
                currentEntry->boneMap[src] = tgt;
                currentEntry->boneConfidence[src] = conf;
            }
        } else if (currentEntry && line.rfind("PATTERN:", 0) == 0) {
            // Format: PATTERN:sourceBone:targetBone:avgDist:successRate:sampleCount
            std::string rest = line.substr(8);
            std::vector<std::string> parts;
            size_t start = 0;
            while (start < rest.size()) {
                size_t pos = rest.find(':', start);
                if (pos == std::string::npos) pos = rest.size();
                parts.push_back(rest.substr(start, pos - start));
                if (pos == rest.size()) break;
                start = pos + 1;
            }
            if (parts.size() >= 5) {
                LearningEntry::TransferPattern p;
                p.sourceBone = parts[0];
                p.targetBone = parts[1];
                p.avgDistance = std::stof(parts[2]);
                p.successRate = std::stof(parts[3]);
                p.sampleCount = static_cast<uint32_t>(std::stoul(parts[4]));
                currentEntry->transferPatterns.push_back(p);
            }
        } else if (currentEntry && line.rfind("SYMMETRY:", 0) == 0) {
            std::string rest = line.substr(9);
            size_t arrow = rest.find("->");
            if (arrow != std::string::npos) {
                currentEntry->symmetryPairs.emplace_back(
                    rest.substr(0, arrow), rest.substr(arrow + 2));
            }
        } else if (currentEntry && line.rfind("SOCKET:", 0) == 0) {
            currentEntry->socketBones.push_back(line.substr(7));
        } else if (currentEntry && line.rfind("WEAPON:", 0) == 0) {
            currentEntry->weaponBones.push_back(line.substr(7));
        }
    }
    
    updateEntryStats(*currentEntry);
    return ResultVoid::ok();
}

ResultVoid SelfLearningDatabase::save(const std::filesystem::path& path) const {
    std::ofstream file(path, std::ios::binary);
    if (!file) {
        return ResultVoid::fail("Cannot write learning database: " + path.string(), "SELF_LEARN");
    }
    
    file << "# Metin2 Self-Learning Database\n";
    file << "# Generated by m2rig\n\n";
    
    for (const auto& [key, entry] : getEntries()) {
        file << "ENTRY:" << key << "\n";
        
        for (const auto& [src, tgt] : entry.boneMap) {
            float conf = entry.boneConfidence.count(src) ? entry.boneConfidence.at(src) : 1.0f;
            file << "BONEMAP:" << src << "->" << tgt << ":" << conf << "\n";
        }
        
        for (const auto& p : entry.transferPatterns) {
            file << "PATTERN:" << p.sourceBone << ":" << p.targetBone << ":"
                 << p.avgDistance << ":" << p.successRate << ":" << p.sampleCount << "\n";
        }
        
        for (const auto& [a, b] : entry.symmetryPairs) {
            file << "SYMMETRY:" << a << "->" << b << "\n";
        }
        
        for (const auto& s : entry.socketBones) {
            file << "SOCKET:" << s << "\n";
        }
        
        for (const auto& w : entry.weaponBones) {
            file << "WEAPON:" << w << "\n";
        }
        
        file << "\n";
    }
    
    return ResultVoid::ok();
}

LearningEntry* SelfLearningDatabase::getOrCreateEntry(const Gr2CharacterProfile& profile) {
    std::string key = profile.profileId.empty() 
        ? (profile.race + "_" + profile.gender + "_" + profile.variant)
        : profile.profileId;
    return getOrCreateEntryByKey(key);
}

LearningEntry* SelfLearningDatabase::getOrCreateEntryByKey(const std::string& key) {
    auto it = entries_.find(key);
    if (it == entries_.end()) {
        LearningEntry entry;
        entry.characterKey = key;
        auto [newIt, _] = entries_.emplace(key, std::move(entry));
        return &newIt->second;
    }
    return &it->second;
}

const LearningEntry* SelfLearningDatabase::getEntry(const std::string& characterKey) const {
    auto it = entries_.find(characterKey);
    return it != entries_.end() ? &it->second : nullptr;
}

void SelfLearningDatabase::recordTransfer(const Gr2CharacterProfile&,  // sourceProfile (unused, kept for API symmetry)
                                          const Gr2CharacterProfile& targetProfile,
                                          const std::string& sourceBone,
                                          const std::string& targetBone,
                                          float distance,
                                          bool success) {
    LearningEntry* entry = getOrCreateEntry(targetProfile);
    
    // Update bone map
    if (!entry->boneMap.contains(sourceBone)) {
        entry->boneMap[sourceBone] = targetBone;
        entry->boneConfidence[sourceBone] = success ? 1.0f : 0.3f;
    } else {
        // Update confidence based on success
        float& conf = entry->boneConfidence[sourceBone];
        conf = conf * 0.9f + (success ? 0.1f : -0.1f);
        conf = std::clamp(conf, 0.0f, 1.0f);
    }
    
    // Update transfer pattern
    for (auto& p : entry->transferPatterns) {
        if (p.sourceBone == sourceBone && p.targetBone == targetBone) {
            p.distanceSamples.push_back(distance);
            if (p.distanceSamples.size() > 100) p.distanceSamples.erase(p.distanceSamples.begin());
            p.avgDistance = std::accumulate(p.distanceSamples.begin(), p.distanceSamples.end(), 0.0f) 
                          / p.distanceSamples.size();
            p.successRate = p.successRate * 0.95f + (success ? 0.05f : 0.0f);
            p.sampleCount++;
            updateEntryStats(*entry);
            return;
        }
    }
    
    // New pattern
    LearningEntry::TransferPattern p;
    p.sourceBone = sourceBone;
    p.targetBone = targetBone;
    p.avgDistance = distance;
    p.successRate = success ? 1.0f : 0.0f;
    p.sampleCount = 1;
    p.distanceSamples = {distance};
    entry->transferPatterns.push_back(p);
    
    updateEntryStats(*entry);
}

void SelfLearningDatabase::recordVertexAffinities(const Gr2CharacterProfile& profile,
                                                  const Mesh& mesh,
                                                  const Skeleton& skeleton) {
    LearningEntry* entry = getOrCreateEntry(profile);
    
    // Clear old affinities
    entry->vertexAffinities.clear();
    
    // For each bone, compute vertex affinity
    for (size_t b = 0; b < skeleton.bones.size(); ++b) {
        const Bone& bone = skeleton.bones[b];
        LearningEntry::VertexAffinity affinity;
        affinity.boneName = bone.name;
        affinity.bonePosition = {bone.globalTransform.m[3][0], bone.globalTransform.m[3][1], bone.globalTransform.m[3][2]};
        
        float maxDist = 0.0f;
        for (size_t v = 0; v < mesh.vertices.size(); ++v) {
            float totalWeight = 0.0f;
            for (const auto& inf : mesh.vertices[v].influences) {
                if (inf.bone == b) {
                    totalWeight += inf.weight;
                }
            }
            if (totalWeight > 0.01f) { // Threshold for significant influence
                affinity.vertexWeights.emplace_back(static_cast<uint32_t>(v), totalWeight);
                float dist = distance(mesh.vertices[v].position, affinity.bonePosition);
                maxDist = std::max(maxDist, dist);
            }
        }
        affinity.influenceRadius = maxDist;
        if (!affinity.vertexWeights.empty()) {
            entry->vertexAffinities.push_back(std::move(affinity));
        }
    }
}

std::optional<std::string> SelfLearningDatabase::getBestMapping(const Gr2CharacterProfile&,  // sourceProfile (unused, kept for API symmetry)
                                                                const Gr2CharacterProfile& targetProfile,
                                                                const std::string& sourceBone) const {
    std::string key = targetProfile.profileId.empty() 
        ? (targetProfile.race + "_" + targetProfile.gender + "_" + targetProfile.variant)
        : targetProfile.profileId;
    const LearningEntry* entry = getEntry(key);
    if (!entry) return std::nullopt;
    
    auto it = entry->boneMap.find(sourceBone);
    if (it != entry->boneMap.end()) {
        float conf = entry->boneConfidence.count(sourceBone) ? entry->boneConfidence.at(sourceBone) : 0.5f;
        if (conf > 0.3f) return it->second;
    }
    
    // Fallback: find pattern with highest success rate
    std::optional<std::string> best;
    float bestScore = 0.0f;
    for (const auto& p : entry->transferPatterns) {
        if (p.sourceBone == sourceBone && p.successRate > bestScore) {
            bestScore = p.successRate;
            best = p.targetBone;
        }
    }
    
    return best;
}

float SelfLearningDatabase::getTransferConfidence(const Gr2CharacterProfile&,  // sourceProfile (unused)
                                                  const Gr2CharacterProfile& targetProfile,
                                                  const std::string& sourceBone,
                                                  const std::string& targetBone) const {
    std::string key = targetProfile.profileId.empty() 
        ? (targetProfile.race + "_" + targetProfile.gender + "_" + targetProfile.variant)
        : targetProfile.profileId;
    const LearningEntry* entry = getEntry(key);
    if (!entry) return 0.5f;
    
    auto it = entry->boneConfidence.find(sourceBone);
    if (it != entry->boneConfidence.end() && entry->boneMap.count(sourceBone) 
        && entry->boneMap.at(sourceBone) == targetBone) {
        return it->second;
    }
    
    // Check patterns
    for (const auto& p : entry->transferPatterns) {
        if (p.sourceBone == sourceBone && p.targetBone == targetBone) {
            return p.successRate;
        }
    }
    
    return 0.5f; // Default neutral confidence
}

